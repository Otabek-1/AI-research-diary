import { readdir, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const locales = ["en"];
const imports = [];
const collections = [];

for (const locale of locales) {
  const directory = join(root, "content", "locales", locale);
  let names = [];
  try {
    names = (await readdir(directory)).filter((name) => name.endsWith(".json")).sort();
  } catch {
    names = [];
  }
  const variables = [];
  for (const [index, name] of names.entries()) {
    const variable = `${locale}Document${index}`;
    const path = relative(join(root, "src", "lib"), join(directory, name)).replaceAll("\\", "/");
    imports.push(`import ${variable} from ${JSON.stringify(`./${path}`)};`);
    variables.push(variable);
  }
  collections.push(`  ${locale}: [${variables.join(", ")}],`);
}

const source = `// Generated by scripts/generate-content-index.mjs. Do not edit by hand.\n${imports.join("\n")}\n\nexport const generatedDocuments = {\n${collections.join("\n")}\n} as const;\n`;
await writeFile(join(root, "src", "lib", "generated-content.ts"), source);